export function EntityIcon({ name, size = 16, color, className }: { name: string; size?: number; color?: string; className?: string }) {
  const Icon = ENTITY_ICONS[name] ?? Circle;
  return <Icon size={size} color={color} className={className} aria-hidden />;
}

